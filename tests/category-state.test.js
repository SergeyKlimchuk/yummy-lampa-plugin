'use strict';
const assert=require('assert'),fs=require('fs'),vm=require('vm');
let account={user_id:7,login:'demo'},token='one',now=1000000,events=[];
const context={console,Date:{now:()=>now},document:{},$:()=>({trigger:(name,args)=>events.push({name,args})})};
context.window=context;
context.LampaYaniAuth={get:()=>account,token:()=>token};
vm.runInNewContext(fs.readFileSync('src/ui-card-model.js','utf8'),context);
const api=context.LampaYaniCardModel,model=api.create({t:x=>x});
const normalized=x=>JSON.parse(JSON.stringify(api.normalizeListState(x)));
assert.deepStrictEqual(normalized({user:{list:{list:{id:0},is_fav:true}}}),{listKnown:true,listId:0,favoriteKnown:true,favorite:true});
assert.deepStrictEqual(normalized({user_list:{id:2,is_favorite:false}}),{listKnown:true,listId:2,favoriteKnown:true,favorite:false});
assert.deepStrictEqual(normalized({list_state:{list:null,is_fav:true}}),{listKnown:true,listId:null,favoriteKnown:true,favorite:true});
assert.strictEqual(normalized({}).listKnown,false,'missing API membership is unknown, not a fabricated empty list');
assert.strictEqual(normalized({yani_list_id:null,yani_list_known:false}).listKnown,false);
let card=model.toCard({anime_id:9,title:'Title',user:{list:{list:{id:0},is_fav:true}}});
assert.strictEqual(card.yani_list_id,0);assert.strictEqual(card.yani_is_favorite,true);
const owner=api.listOwner();assert.strictEqual(api.commitListState(card,{listId:1},owner),true);
let cached=model.toCard({anime_id:9,user:{list:{list:{id:0},is_fav:true}}});
assert.strictEqual(cached.yani_list_id,1,'successful category write overrides stale cached search/detail data');
assert.strictEqual(cached.yani_is_favorite,true,'main category does not clear independent favorite');
api.commitListState(card,{listId:null},owner);api.commitListState(card,{favorite:true},owner);
cached=model.toCard({anime_id:9,user:{list:{list:{id:2},is_fav:false}}});
assert.strictEqual(cached.yani_list_id,null,'explicit removal must survive reopening stale detail');assert.strictEqual(cached.yani_list_known,true);assert.strictEqual(cached.yani_is_favorite,true);
token='refreshed';assert.strictEqual(api.applyListState({yani_id:9,yani_list_id:2}).yani_list_id,null,'token rotation must preserve successful category write');
account={user_id:8,login:'other'};token='other';
assert.strictEqual(model.toCard({anime_id:9,user:{list:{list:{id:2}}}}).yani_list_id,2,'account switch must discard old overrides');
assert.strictEqual(api.commitListState(card,{listId:0},owner),false,'late mutation of previous account must not enter new owner cache');
account={login:'hydrating'};token='new';const hydration=api.listOwner();api.commitListState({yani_id:2},{listId:5},hydration);
account={login:'hydrating',user_id:12};token='rotated';
assert.strictEqual(api.applyListState({yani_id:2}).yani_list_id,5,'hydrating user id and rotating token is the same account');
now+=300001;assert.strictEqual(api.applyListState({yani_id:2}).yani_list_id,undefined,'recent write overlay has a bounded lifetime');
for(let i=0;i<161;i++)api.commitListState({yani_id:100+i},{listId:0});
assert.strictEqual(api.applyListState({yani_id:100}).yani_list_id,undefined,'recent writes have a bounded entry count');
assert.ok(events.length>0&&events.every(x=>x.name==='yani:list-state-changed'),'successful writes notify existing views without per-card requests');
console.log('Category state runtime passed: id0/null, favorites, stale search/detail, owner switch/refresh/hydration, bounded cache');
