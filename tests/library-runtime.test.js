'use strict';
const assert = require('assert');
const {tvEnvironment, $, deferred, settle} = require('./helpers/tv-dom');
const definitions = ['watching','planned','completed','dropped','favorites','postponed'].map((key,id) => ({id,key,title:key}));
const anime = count => Array.from({length:count},(_,index) => ({anime_id:index+1,title:'Anime '+(index+1),date:1700000000+index}));
function setup() {
    const env = tvEnvironment(), requests = [], counts = deferred(), layoutCalls = [];
    env.load('ui-account-list-controls.js'); env.load('ui-library.js');
    let sortOptions;
    env.context.LampaYaniChoicePanel = env.context.window.LampaYaniChoicePanel = {show: options => { sortOptions = options; env.context.Lampa.Controller.toggle('yani_choice_panel'); return {destroy() { options.onClose('destroy'); }}; }};
    const component = env.context.LampaYaniLibrary.create({}, {t:key=>key, definitions, loadItems:definition=> { const next=deferred(); requests.push({definition,next}); return next.promise; }, loadCounts:()=>counts.promise, toCard:value=>value, cardRender:()=>env.calls.push(['decorate']), syncCardLayout:scope=> { assert.ok(env.document.documentElement.contains(scope[0]), 'layout is measured only after the native grid is mounted'); const cards=scope.find('.card'); assert.ok(cards.length<=30); layoutCalls.push(cards.nodes.slice()); }, goBack:()=>env.calls.push(['back'])});
    component.activity={loader:value=>env.calls.push(['loader',value])}; $(env.document.body).append(component.render());
    component.create(); component.start();
    return Object.assign(env,{component,requests,counts,layoutCalls,sort:()=>sortOptions});
}
(async () => {
    let env=setup(); await settle();
    assert.equal(env.requests[0].definition.id,-1);
    assert.equal(env.component.render().find('.yani-library__tab').length,7);
    assert.equal(env.component.render().find('.yani-library__count').first().text(),'—');
    env.counts.resolve({watching:5,planned:3,completed:8,dropped:1,favorites:4,postponed:2});
    env.requests[0].next.resolve(anime(600)); await settle();
    assert.equal(env.component.render().find('.yani-library__count').first().text(),'19','All excludes duplicate favorites');
    assert.equal(env.component.render().find('.card.selector').length,30,'600 entries only create one 30-card page');
    assert.equal(env.buildCalls[0].total_pages,1,'native infinite paging cannot grow the live DOM');
    assert.equal(env.calls.filter(call=>call[0]==='decorate').length,30,'production renderer decorates every card');
    assert.equal(env.layoutCalls.length,1,'one mounted layout pass per page, without repeating decoration');
    assert.equal(env.layoutCalls[0].length,30);
    const initialCard=env.component.render().find('.card.selector')[0];
    env.component.render().find('.yani-library__page').first().trigger('hover:enter');
    assert.equal(env.component.render().find('.card.selector').length,30);
    assert.equal(env.component.render().find('.card.selector')[0].record.anime_id,570,'recent sorting and explicit page2 work');
    assert.equal(env.component.render().find('.yani-library__page-number').text(),'2 / 20');
    assert.equal(env.layoutCalls.length,2,'next page gets a single mounted layout pass');
    assert.equal(env.calls.filter(call=>call[0]==='decorate').length,60,'mounting does not bind each card a second time');
    assert.equal(env.document.documentElement.contains(initialCard),false,'old native card DOM gets released');
    const prior=env.component.render().find('.card.selector')[0];
    env.component.render().find('.yani-library__tab')[1] && $(env.component.render().find('.yani-library__tab')[1]).trigger('hover:enter'); await settle();
    assert.equal(env.component.render().find('.card.selector')[0],prior,'pending category keeps original card DOM without flashing');
    $(env.component.render().find('.yani-library__tab')[2]).trigger('hover:enter'); await settle();
    env.requests[2].next.resolve([{anime_id:2000,title:'Latest category'}]); await settle();
    env.requests[1].next.resolve([{anime_id:1000,title:'Stale category'}]); await settle();
    assert.equal(env.component.render().find('.card.selector')[0].record.anime_id,2000,'older responses cannot replace latest category');
    assert.equal(env.component.render().find('.yani-library__tab').filter('.is-selected').attr('data-category'),'planned');
    assert.equal(env.layoutCalls.length,3,'stale category responses do not repaint mounted cards');
    let emitted=0; env.component.on('controller',()=>emitted++); env.component.start(); assert.ok(emitted>0,'shell receives recreated native controllers');
    env.component.render().find('.yani-library__sort').trigger('hover:enter');
    assert.equal(env.sort().items.length,5); assert.equal(env.sort().items[0].selected,true);
    env.context.Lampa.Controller.toggle('yani_library_tabs'); env.sort().onSelect({key:'title'});
    assert.equal(env.component.render().find('.yani-library__sort').text(),'list_sort: list_sort_title');
    env.component.destroy();

    env=setup(); await settle(); env.requests[0].next.resolve(anime(2)); await settle();
    $(env.component.render().find('.yani-library__tab')[1]).trigger('hover:enter'); await settle();
    env.context.Lampa.Controller.toggle('yani_tv_rail'); const before=env.focusCalls.length, builds=env.buildCalls.length;
    env.requests[1].next.resolve(anime(4)); await settle();
    assert.equal(env.buildCalls.length,builds,'native build is deferred while rail owns Navigator');
    assert.equal(env.enabled().name,'yani_tv_rail'); assert.equal(env.focusCalls.length,before,'async categories never steal focus from rail');
    env.context.Lampa.Controller.toggle('content');
    assert.equal(env.component.render().find('.card.selector').length,4,'returning from rail commits deferred grid');
    env.component.start();
    $(env.component.render().find('.yani-library__tab')[2]).trigger('hover:enter'); await settle();
    env.context.Lampa.Controller.toggle('yani_choice_panel'); const panelFocus=env.focusCalls.length;
    env.requests[2].next.resolve(anime(3)); await settle();
    assert.equal(env.enabled().name,'yani_choice_panel'); assert.equal(env.focusCalls.length,panelFocus,'async response leaves overlay focus untouched');
    env.component.destroy();

    env=setup(); await settle(); env.auth.user_id=77; env.auth.login='other'; env.auth.token='other';
    env.requests[0].next.resolve(anime(6)); env.counts.resolve({watching:99}); await settle();
    assert.equal(env.component.render().find('.card.selector').length,0,'account switch rejects stale records');
    assert.equal(env.layoutCalls.length,0,'stale account responses never measure or paint cards');
    assert.equal(env.component.render().find('.yani-library__count').first().text(),'—'); env.component.destroy();
    env=setup(); await settle(); env.component.destroy(); env.requests[0].next.resolve(anime(7)); await settle();
    assert.equal(env.buildCalls.length,0,'destroyed page never builds delayed results');
    assert.equal(env.layoutCalls.length,0,'destroyed page never runs delayed layout work');
    console.log('library-runtime: bounded grids, preserved DOM, sorting, focus and account guards passed');
})().catch(error=>{ console.error(error); process.exitCode=1; });
