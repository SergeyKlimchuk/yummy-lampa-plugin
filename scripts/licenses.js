'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DATA_PATH = 'src/license-data.js';
const START = '/* YUMMY_LICENSE_NOTICES_START\n';
const END = '\nYUMMY_LICENSE_NOTICES_END */\n';
const FORK_NOTICE = '--- MIT applies only to the fork contributions identified in LICENSE; it does not relicense upstream additions ---';

function readText(root, file) {
    return fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n?/g, '\n');
}

function loadRegistry(root) {
    const registry = JSON.parse(readText(root, 'licenses.json'));
    if (registry.schemaVersion !== 1 || !Array.isArray(registry.entries)) throw new Error('Invalid license registry');
    const seen = new Set();
    const entries = registry.entries.map(entry => {
        if (!entry || !/^[a-z0-9-]+$/.test(entry.id || '') || seen.has(entry.id)) throw new Error('Invalid or duplicate license entry id');
        seen.add(entry.id);
        for (const key of ['title', 'scope', 'notice']) {
            if (typeof entry[key] !== 'string' || !entry[key].trim()) throw new Error('Missing license entry ' + key + ': ' + entry.id);
        }
        if (!['confirmed', 'unconfirmed', 'third-party'].includes(entry.status)) throw new Error('Invalid license status: ' + entry.id);
        if (entry.license !== null && typeof entry.license !== 'string') throw new Error('Invalid license name: ' + entry.id);
        if (!Array.isArray(entry.sources) || entry.sources.some(source => !source || typeof source.title !== 'string' || !/^https?:\/\//.test(source.url || ''))) throw new Error('Invalid license sources: ' + entry.id);
        let licenseText = null;
        if (entry.licenseFile !== null) {
            if (typeof entry.licenseFile !== 'string' || !/^LICENSES\/[\w.-]+\.txt$/.test(entry.licenseFile)) throw new Error('Invalid license file: ' + entry.id);
            licenseText = readText(root, entry.licenseFile);
            if (!licenseText.trim()) throw new Error('Empty license file: ' + entry.id);
        }
        if (entry.status === 'confirmed' && (!entry.license || !licenseText)) throw new Error('Confirmed component needs its license text: ' + entry.id);
        if (entry.status === 'unconfirmed' && (entry.license !== null || licenseText !== null)) throw new Error('Unconfirmed component cannot claim a license: ' + entry.id);
        return Object.assign({}, entry, {licenseText});
    });
    return {schemaVersion: 1, entries};
}

function dataScript(root) {
    const data = JSON.stringify(loadRegistry(root)).replace(/[<\u2028\u2029]/g, value => '\\u' + value.charCodeAt(0).toString(16).padStart(4, '0'));
    return '// Generated by scripts/licenses.js from licenses.json and LICENSES/. Do not edit.\n' +
        '(function (window) {\n    \'use strict\';\n    window.LampaYaniLicenseData = ' + data + ';\n}(window));\n';
}

function stripNotices(source) {
    if (!source.startsWith(START)) return source;
    const end = source.indexOf(END, START.length);
    if (end < 0) throw new Error('Unterminated license notices header');
    return source.slice(end + END.length);
}

function noticesHeader(options) {
    options = options || {};
    const root = options.root || ROOT;
    const scopes = [
        'YummyAnime Lampa: scoped license notices.',
        'Historical upstream code: MIT, with its original copyright notice below.',
        'Later upstream additions have unconfirmed licensing; these notices do not grant rights to them.',
        'Third-party logos, posters and texts retain their separate rights and are not covered by these MIT grants.',
        'See LICENSE, licenses.json and THIRD_PARTY_NOTICES.md for scope, sources and limitations.',
        '',
        '--- Historical upstream MIT notice ---',
        readText(root, 'LICENSES/MIT-original.txt').trimEnd()
    ];
    if (options.includeFork !== false) scopes.push('',
        FORK_NOTICE,
        readText(root, 'LICENSES/MIT-fork.txt').trimEnd());
    const text = scopes.join('\n');
    if (text.includes('*/')) throw new Error('License notice contains a comment terminator');
    return START + text + END;
}

function withNotices(source, options) {
    return noticesHeader(options) + stripNotices(source);
}

function forkNoticePresent(source) {
    // This only preserves this fork's explicit publication metadata. A version
    // number is not evidence of authorship or a copyright/license grant.
    const header = source.startsWith(START) ? source.slice(0, source.indexOf(END)) : '';
    return header.includes(FORK_NOTICE) || /\bwindow\.LampaYaniLicenseData\s*=/.test(stripNotices(source));
}

function sync(options) {
    options = options || {};
    const root = options.root || ROOT;
    const artifacts = [{file: DATA_PATH, expected: dataScript(root)}];
    for (const file of ['index.js', 'stable/index.js']) {
        const full = path.join(root, file);
        if (!fs.existsSync(full)) continue;
        const source = fs.readFileSync(full, 'utf8');
        artifacts.push({file, expected: withNotices(source, {root, includeFork: file !== 'stable/index.js' || forkNoticePresent(source)})});
    }
    artifacts.forEach(artifact => {
        const full = path.join(root, artifact.file);
        const actual = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
        if (actual === artifact.expected) return;
        if (options.check) throw new Error(artifact.file + ' license data/notices are out of date. Run node scripts/licenses.js');
        fs.mkdirSync(path.dirname(full), {recursive: true});
        fs.writeFileSync(full, artifact.expected);
    });
    return artifacts.map(artifact => artifact.file);
}

if (require.main === module) {
    const args = process.argv.slice(2);
    if (args.some(arg => arg !== '--check')) throw new Error('Usage: node scripts/licenses.js [--check]');
    sync({check: args.includes('--check')});
    console.log(args.includes('--check') ? 'License data and entry notices match canonical sources' : 'Updated license data and entry notices');
}

module.exports = {DATA_PATH, START, END, loadRegistry, dataScript, noticesHeader, stripNotices, withNotices, forkNoticePresent, sync};
